"""Generate firmware/field/stations.py from the built viewer data.

The Cardputer needs a fixed station order per line so the operator can walk the
network with two keys. The order comes from the chained GTFS/OSM segments in
`web/public/data/v1/network.json`; names come from `stations.json` with accents
folded, because the device font has no reliable glyphs for them.

Run after any rebuild that changes station order:

    python3 pipeline/gen_firmware_stations.py
"""

from __future__ import annotations

import json
import unicodedata
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "web" / "public" / "data" / "v1"
OUT = ROOT / "firmware" / "field" / "stations.py"


def ascii_name(text: str) -> str:
    folded = unicodedata.normalize("NFKD", text)
    return "".join(ch for ch in folded if not unicodedata.combining(ch))


def ordered_stations(segments: list[dict[str, str]]) -> list[str]:
    following: dict[str, str] = {}
    for segment in segments:
        following[segment["from"]] = segment["to"]
    targets = set(following.values())
    heads = [station for station in following if station not in targets]
    if len(heads) != 1:
        raise RuntimeError(f"expected one line head, found {heads}")
    order = [heads[0]]
    while order[-1] in following:
        order.append(following[order[-1]])
    if len(order) != len(segments) + 1:
        raise RuntimeError(
            f"segment chain has {len(order) - 1} edges, expected {len(segments)}"
        )
    return order


def main() -> None:
    network = json.loads((DATA / "network.json").read_text())
    stations = json.loads((DATA / "stations.json").read_text())
    by_id = {station["id"]: station for station in stations}

    lines: list[str] = []
    total = 0
    for line in network["lines"]:
        order = ordered_stations(line["segments"])
        rows = []
        for station_id in order:
            station = by_id[station_id]
            rows.append((station_id, ascii_name(station["name"])))
        total += len(rows)
        body = "".join(
            '            ("%s", "%s"),\n' % (station_id, name) for station_id, name in rows
        )
        lines.append(
            '    (\n'
            '        "%s",\n'
            '        "%s",\n'
            '        "%s",\n'
            "        (\n"
            "%s"
            "        ),\n"
            "    ),\n" % (line["id"], ascii_name(line["name"]), line["headsign"], body)
        )

    text = (
        "# Generated by pipeline/gen_firmware_stations.py. Do not edit.\n"
        "# (line_id, line_name, headsign, ((station_id, display_name), ...))\n"
        "LINES = (\n" + "".join(lines) + ")\n"
    )
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(ROOT)}: {total} stations")


if __name__ == "__main__":
    main()
